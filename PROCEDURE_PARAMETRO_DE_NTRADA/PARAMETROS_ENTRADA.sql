USE FERRETERIA;

-- 1.-P.A. QUE MUESTRE LAS ENTREGAS REALIZADAS DE UNA HERRAMIENTA CUYO CODIGO
-- SE INTRODUCE POR PARAMETRO DE ENTRADA,
-- A).- SIN VERIFICACION. 

DELIMITER //
CREATE PROCEDURE PA_PE1(IN CODI CHAR(6))
BEGIN
SELECT * FROM ENTREGA
WHERE CODIGO=CODI;
END //
DELIMITER ;
CALL PA_PE1('HER001');
SELECT *FROM HERRAMIENTA;

-- B).- CON VERIFICACION, UTILIZANDO EXISTS.
DELIMITER //
CREATE PROCEDURE PA_PE1_B(IN CODI CHAR(6))
BEGIN
IF EXISTS(SELECT CODIGO FROM HERRAMIENTA WHERE CODIGO=CODI)THEN
SELECT * FROM ENTREGA
WHERE CODIGO=CODI;
ELSE SELECT 'NO EXISTE ESA HERRAMIENTA' AS MENSAJE; END IF;
END //
DELIMITER ;
CALL PA_PE1_B('HER023');


-- 2.-P.A QUE MUESTRE EL SALDO EN EL ALMACEN DE UNA HERRAMIENTA CUYA 
-- DESCRIPCION SE CONOCE (PARAMETRO DE ENTRADA)
DELIMITER //
CREATE PROCEDURE PAPE2(IN DES VARCHAR(35))
BEGIN 
IF EXISTS(SELECT DESCRIPCION FROM HERRAMIENTA WHERE DESCRIPCION=DES)THEN
SELECT A.CSALDO FROM ALMACEN A JOIN  HERRAMIENTA H ON A.CODIGO=H.CODIGO
WHERE H.DESCRIPCION=DES;

ELSE SELECT 'No hay esa herramienta' AS MENSAJE ;END IF;
END //
DELIMITER ;




