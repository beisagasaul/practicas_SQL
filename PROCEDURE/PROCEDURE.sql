CREATE PROCEDURE PA9()
BEGIN
SELECT H.DESCRIPCION,AVG(E.CANTIDAD),MIN(E.CANTIDAD)
FROM  HERRAMIENTA H JOIN ENTREGA E ON H.CODIGO=E.CODIGO
WHERE  MONTH(E.FECHA) BETWEEN 1 AND 6 AND YEAR(E.FECHA)=2026
GROUP BY H.CODIGO ,H.DESCRIPCION 
HAVING SUM(E.CANTIDAD)<(
    SELECT MAX(CANTIDAD)*0.85
    FROM ENTREGA

    )
ORDER BY  H.DESCRIPCION ASC;

END //
DELIMITER ;

CALL PA9();


