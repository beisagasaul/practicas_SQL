DELIMITER //
CREATE PROCEDURE PA4()
BEGIN
SELECT H.DESCRIPCION,SUM(E.CANTIDAD) AS 'CANTIDAD TOTAL'
FROM  HERRAMIENTA H JOIN ENTREGA E ON H.CODIGO =E.CODIGO
WHERE H.PRECIO >=10
GROUP BY H.CODIGO,H.DESCRIPCION;

END //
DELIMITER ;

CALL PA4()

