USE FERRETERIA;
DELIMITER //
CREATE PROCEDURE PA1( )
BEGIN
SELECT DESCRIPCION 
FROM HERRAMIENTA
WHERE PRECIO BETWEEN 10 AND 20;
END 
DELIMITER ;

CALL PA1()

-- 2
DELIMITER //
CREATE PROCEDURE PA2()
BEGIN 
SELECT DESCRIPCION
FROM HERRAMIENTA
WHERE DESCRIPCION LIKE 'A%';
END //
DELIMITER ;

CALL PA2();

-- 3
DELIMITER //
CREATE PROCEDURE PA3()
BEGIN
SELECT AVG(E.CANTIDAD) AS 'PROMEDIO'
FROM ENTREGA E JOIN HERRAMIENTA H 
ON E.CODIGO=H.CODIGO
WHERE MONTH(E.FECHA)=8 AND YEAR(E.FECHA)=2022;
END //
DELIMITER ;

CALL PA3();
-- 4
DELIMITER //
CREATE PROCEDURE PA4()
BEGIN
SELECT H.DESCRIPCION,SUM(E.CANTIDAD) AS 'CANTIDAD TOTAL'
FROM  HERRAMIENTA H JOIN ENTREGA E ON H.CODIGO =E.CODIGO
WHERE H.PRECIO >=10
GROUP BY H.CODIGO,H.DESCRIPCION;

END //
DELIMITER ;

CALL PA4()

-- 5
DELIMITER //
CREATE PROCEDURE PA5()
BEGIN
  SELECT H.DESCRIPCION 
  FROM HERRAMIENTA H JOIN 
  ALMACEN A ON H.CODIGO=A.CODIGO
  WHERE A.CSALDO >0 
  ORDER BY  H.DESCRIPCION ASC  ;
END //
DELIMITER ;
CALL PA5();

-- 6
DELIMITER //
CREATE PROCEDURE PA6()
BEGIN
SELECT H.DESCRIPCION,SUM(H.PRECIO*E.CANTIDAD) AS 'COSTO TOTAL'
FROM HERRAMIENTA H JOIN ENTREGA E ON H.CODIGO=E.CODIGO
WHERE  YEAR(E.FECHA)=2018
GROUP BY H.DESCRIPCION
HAVING COUNT(E.CANTIDAD)>=2;
END //
DELIMITER ;

CALL PA6()

-- 7
DELIMITER  //
CREATE PROCEDURE PA7()
BEGIN
SELECT DESCRIPCION ,MAX(PRECIO)
FROM HERRAMIENTA
WHERE DESCRIPCION LIKE '%A' OR
DESCRIPCION LIKE '%E'OR
DESCRIPCION LIKE '%I' OR
DESCRIPCION LIKE '%O'OR 
DESCRIPCION LIKE '%U'
GROUP BY CODIGO,DESCRIPCION ;
END //
DELIMITER ;

CALL PA7();

-- 8 -- CON SUBCONSULTAS
DELIMITER //
CREATE PROCEDURE PA8()
BEGIN
SELECT DESCRIPCION
FROM HERRAMIENTA
WHERE PRECIO = (SELECT
   MIN(PRECIO)
   FROM HERRAMIENTA
);
END //
DELIMITER ;

CALL PA8();


-- 9
DELIMITER //
CREATE PROCEDURE PA9()
BEGIN
SELECT H.DESCRIPCION,AVG(E.CANTIDAD),MIN(E.CANTIDAD)
FROM  HERRAMIENTA H JOIN ENTREGA E ON H.CODIGO=E.CODIGO
WHERE  MONTH(E.FECHA) BETWEEN 1 AND 6 AND YEAR(E.FECHA)=2026
GROUP BY H.CODIGO ,H.DESCRIPCION 
HAVING SUM(E.CANTIDAD)<(
    SELECT MAX(CANTIDAD)*0.85
    FROM ENTREGA

    )
ORDER BY  H.DESCRIPCION ASC;

END //
DELIMITER ;

CALL PA9();


