use FERRETERIA
DELIMITER //
CREATE PROCEDURE PA10()
BEGIN
SELECT  H.DESCRIPCION,(SUM(A.CSALIDA)/
NULLIF(SUM(A.CENTRADA),0))*100 AS 'PORCENTAJE DE SALIDA',

(SUM(A.CSALDO)/
NULLIF(SUM(A.CENTRADA),0))*100 AS 'PORCENTAJE DE SALDO'

FROM  HERRAMIENTA H JOIN ALMACEN A ON H.CODIGO=A.CODIGO
WHERE 
H.DESCRIPCION LIKE '__S%' OR
H.DESCRIPCION LIKE '__M%' OR 
H.DESCRIPCION LIKE '__N%' OR
H.DESCRIPCION LIKE '__Z%'
GROUP BY H.CODIGO,H.DESCRIPCION
HAVING SUM(A.CENTRADA)>(SELECT MIN(E.CANTIDAD)*1.20
FROM ENTREGA E)
ORDER BY H.DESCRIPCION ASC;
END //
DELIMITER ;

CALL PA10