CREATE DATABASE FERRETERIA;
USE FERRETERIA;

CREATE TABLE HERRAMIENTA(
    CODIGO CHAR(6)NOT NULL,
    DESCRIPCION VARCHAR(30) DEFAULT '',
    PRECIO DECIMAL (10,2),
    PRIMARY KEY(CODIGO)
  
);
CREATE TABLE ALMACEN(
    CODIGO CHAR(6),
    CENTRADA INT NOT NULL DEFAULT 0,
    CSALIDA INT NOT NULL DEFAULT 0,
    CSALDO INT,
    PRIMARY KEY(CODIGO),
    FOREIGN KEY (CODIGO) REFERENCES HERRAMIENTA(CODIGO),
    CHECK(CENTRADA>=0),
    CHECK(CSALIDA>=0)
);
CREATE TABLE ENTREGA(
    NE INT ,
    FECHA DATETIME NOT NULL ,
    CANTIDA INT,
    CODIGO CHAR(6),
    PRIMARY KEY (NE),
    FOREIGN KEY (CODIGO) REFERENCES HERRAMIENTA (CODIGO)
);



