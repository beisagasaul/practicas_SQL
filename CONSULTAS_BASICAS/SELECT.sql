USE FERRETERIA;


-- SELECT + WHERE
SELECT * 
FROM HERRAMIENTA
WHERE PRECIO>30;

-- ORDER BY + BETWEEN
SELECT *
FROM HERRAMIENTA
WHERE PRECIO>30
ORDER BY PRECIO ASC;

-- BETWEN
SELECT *
FROM HERRAMIENTA
WHERE PRECIO   BETWEEN 20 AND 100 
ORDER BY PRECIO ASC;

-- LIKE
SELECT CODIGO ,DESCRIPCION
FROM HERRAMIENTA
WHERE DESCRIPCION LIKE 'L%'
ORDER BY DESCRIPCION ASC;
-- IN
SELECT *
FROM HERRAMIENTA
WHERE DESCRIPCION IN ('Martillo','Alicate','Taladro');

-- FUNCIONES AGREGADAS
SELECT MIN(PRECIO) AS 'PRECIO MINIMO'
,MAX(PRECIO) AS 'PRECIO MAXIMO'
,AVG(PRECIO) AS 'PRECIO PROMEDIO'
FROM HERRAMIENTA;


-- GROUP  BY
SELECT H.CODIGO ,SUM(E.CANTIDAD) AS 'TOTAL'
FROM HERRAMIENTA H INNER JOIN ENTREGA E
ON H.CODIGO=E.CODIGO
GROUP BY H.CODIGO
HAVING SUM(E.CANTIDAD)>30;


SELECT H.CODIGO,H.DESCRIPCION ,SUM(E.CANTIDAD) AS 'TOTAL ENTREGADO'
FROM HERRAMIENTA H INNER JOIN ENTREGA E ON H.CODIGO=E.CODIGO
WHERE YEAR(E.FECHA)=2025
GROUP BY H.CODIGO,H.DESCRIPCION
HAVING SUM(E.CANTIDAD)>30
ORDER BY SUM(E.CANTIDAD) DESC



