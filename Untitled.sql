use FERRETERIA

DELIMITER //
CREATE PROCEDURE PAVL ()
BEGIN
DECLARE SALDOPROMEDIO INT;
DECLARE SALDOMAXIMO INT;
SELECT AVG(CSALDO) INTO SALDOPROMEDIO FROM ALMACEN;
SELECT MAX(CSALDO) INTO SALDOMAXIMO FROM ALMACEN;


SELECT H.DESCRIPCION
FROM HERRAMIENTA H JOIN ALMACEN A ON H.CODIGO=A.CODIGO 
WHERE CSALDO BETWEEN SALDOPROMEDIO AND SALDOMAXIMO;

END //
DELIMITER ;


