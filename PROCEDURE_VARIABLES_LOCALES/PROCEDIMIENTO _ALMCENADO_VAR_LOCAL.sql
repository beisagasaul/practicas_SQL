DELIMITER //
CREATE PROCEDURE PAVL13()
BEGIN

DECLARE PROM DECIMAL(10,2);
SELECT  AVG(H.PRECIO) INTO PROM
FROM HERRAMIENTA H JOIN ENTREGA E ON H.CODIGO =E.CODIGO
WHERE YEAR(E.FECHA)=2017;
SELECT E.*
FROM ENTREGA E
INNER JOIN HERRAMIENTA H ON E.CODIGO = H.CODIGO
WHERE MONTH(E.FECHA) = 8 AND YEAR(E.FECHA) = 2018
AND H.PRECIO > PROM;

END //
DELIMITER ;



