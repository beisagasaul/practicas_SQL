CREATE PROCEDURE PAVL12()
BEGIN
DECLARE PRECIOALTO FLOAT(10,2);
SELECT MAX(PRECIO) INTO PRECIOALTO FROM HERRAMIENTA;

SELECT DESCRIPCION ,PRECIO 
FROM HERRAMIENTA 
WHERE PRECIO=PRECIOALTO;
END //
